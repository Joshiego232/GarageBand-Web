export function createPedalInstance(pedalId: PedalId): PedalInstance {
  const definition = PEDAL_BY_ID[pedalId];
  return {
    id: uid(),
    pedalId,
    enabled: true,
    params: Object.fromEntries(definition.controls.map((control) => [control.id, control.defaultValue])),
  };
}
